QA.defineTopic({
  id: 'm15-t2', moduleId: 'm15', level: 'MS', title: 'Тесты в Go: табличные тесты и go test',
  asked: [
    'Что такое табличные тесты и почему они идиома Go?',
    'Как устроен тест в Go?',
    'Как запустить тесты с покрытием и обнаружением гонок?',
  ],
  theory: `
## Анатомия теста
Файл \`*_test.go\`, функция \`func TestXxx(t *testing.T)\`, проверки через \`t.Errorf\` /
\`t.Fatalf\`. Внешних библиотек не требуется, но популярна \`testify\` для ассертов.

## Табличные тесты (table-driven) — идиома
Вместо десятка почти одинаковых тестов — срез случаев и цикл по ним:
\`\`\`go
tests := []struct {
    name  string
    a, b  int
    want  int
}{
    {"positive", 2, 3, 5},
    {"zero", 0, 0, 0},
    {"negative", -1, -1, -2},
}
for _, tt := range tests {
    t.Run(tt.name, func(t *testing.T) {
        if got := Add(tt.a, tt.b); got != tt.want {
            t.Errorf("Add(%d,%d) = %d, want %d", tt.a, tt.b, got, tt.want)
        }
    })
}
\`\`\`
Для QA это прямой аналог классов эквивалентности и граничных значений (M2): добавить случай =
добавить строку. \`t.Run\` даёт отдельное имя каждому подслучаю — видно, что именно упало.

## Полезные флаги go test
- \`go test ./...\` — все пакеты.
- \`go test -run TestName\` — конкретный тест.
- \`go test -v\` — подробный вывод.
- \`go test -cover\` / \`-coverprofile\` — покрытие (помня про M3: покрытие ≠ качество).
- \`go test -race\` — **детектор гонок**, критичен для конкурентного кода (см. M4).
- \`go test -bench\` — бенчмарки.
- \`t.Parallel()\` — параллельный запуск подтестов (осторожно с общим состоянием).

## Мышление QA здесь
Табличный тест провоцирует думать наборами случаев. Senior смотрит не «есть ли тест», а покрыты ли
границы и негативные случаи и упадёт ли тест при реальном баге (мутационное мышление, M16).
`,
  answer: `
«Тест в Go — это файл *_test.go и функция TestXxx с *testing.T, проверки через t.Errorf и t.Fatalf,
без внешних раннеров. Идиома — табличные тесты: срез структур со случаями и цикл с t.Run на каждый,
чтобы видеть, какой именно случай упал. Для QA это прямой аналог классов эквивалентности и границ:
добавить случай — добавить строку, что подталкивает думать наборами, а не одним примером. Из флагов
постоянно использую go test ./... для всех пакетов, -run для конкретного, -cover для покрытия —
помня, что покрытие не равно качеству, — и особенно -race, детектор гонок, для конкурентного кода.
Есть -bench для бенчмарков и t.Parallel для параллельных подтестов. Смотрю не на факт теста,
а покрыты ли границы и негатив и упадёт ли тест при настоящем баге.»
`,
  mistake: `
Middle пишет в Go по одному тесту на случай, дублируя код, вместо табличного, и не знает про
\`-race\` — из-за чего гонки в конкурентном коде остаются непойманными. Гонится за \`-cover\`,
принимая процент за качество.
`,
  checklist: `
- Используются ли табличные тесты для наборов случаев?
- Даёт ли t.Run осмысленные имена подслучаям?
- Покрыты ли границы и негативные случаи, а не только happy path?
- Запускается ли конкурентный код с -race?
- Не путается ли -cover с реальным качеством проверки?
`,
  sources: `
- Table-driven tests (go.dev/wiki), пакет testing.
- go test flags; учебник по Go (подключён в модуле).
`,
});

QA.defineTopic({
  id: 'm15-t3', moduleId: 'm15', level: 'MS', title: 'Обработка ошибок и HTTP в Go для тестов',
  asked: [
    'Как в Go обрабатываются ошибки и почему это важно тестировщику?',
    'Как написать проверку HTTP API на Go?',
    'Как тестировать HTTP-обработчик без реальной сети?',
  ],
  theory: `
## Ошибки как значения
В Go нет исключений в привычном смысле: функции возвращают \`error\` как значение, и его проверяют
явно (\`if err != nil\`). Для QA это важно: **необработанная или проглоченная ошибка — частый
дефект**. Смотрите, не игнорируется ли возвращённый \`error\` (\`_ = doSomething()\`),
корректно ли он оборачивается (\`fmt.Errorf("...: %w", err)\`) и различается ли (\`errors.Is\` /
\`errors.As\`). \`panic\` — для действительно исключительных ситуаций, а не для обычных ошибок.

## HTTP-клиент для проверки API
\`net/http\` в стандартной библиотеке: \`http.Get\`, \`http.NewRequest\` + \`client.Do\`, чтение
\`resp.StatusCode\`, \`resp.Body\`, декодирование JSON через \`encoding/json\`. Полноценные
API-проверки пишутся без сторонних библиотек.

## Тестирование HTTP без сети
Два ключевых инструмента, которые senior обязан знать:
- **httptest.NewServer** — поднимает настоящий HTTP-сервер на localhost со своим обработчиком;
  удобно эмулировать внешний сервис (в т.ч. его ошибки и таймауты) для теста клиента.
- **httptest.NewRecorder + прямой вызов хендлера** — тестирование своего HTTP-обработчика без
  поднятия сети вообще: создать запрос, вызвать хендлер, проверить записанный ответ.

## Мышление QA
Проверять не только 200-happy-path, а коды ошибок, таймауты, невалидный/битый JSON в ответе,
пустое тело, неожиданный content-type — то, что реально ломает клиентов. \`httptest\` позволяет
сэмулировать всё это детерминированно, без флейки от реального внешнего сервиса.
`,
  answer: `
«В Go ошибки — это значения: функции возвращают error, и его проверяют явно через if err != nil,
исключений в привычном смысле нет. Для QA это точка внимания: проглоченная ошибка через _ =
или потерянное оборачивание %w — частый дефект; смотрю, обрабатывается ли error и различается ли
через errors.Is/As. API проверяю стандартным net/http и encoding/json, сторонних библиотек не нужно.
Ключевое — тестирование HTTP без реальной сети: httptest.NewServer поднимает настоящий сервер
на localhost, чтобы детерминированно сэмулировать внешний сервис с его ошибками и таймаутами,
а httptest.NewRecorder с прямым вызовом хендлера проверяет мой обработчик вообще без сети.
Проверяю не только 200, а коды ошибок, таймауты, битый и пустой JSON, неожиданный content-type —
то, что реально ломает клиентов, — и httptest даёт это без флейки от живого сервиса.»
`,
  mistake: `
Middle в Go-тестах проверяет только успешный путь и реальный внешний сервис (флейки, зависимость
от сети), не зная про httptest. И не проверяет обработку ошибок — а в Go проглоченный \`error\`
это целый класс дефектов.
`,
  checklist: `
- Проверяется ли, что error не игнорируется и корректно оборачивается?
- Используется ли httptest вместо реального внешнего сервиса в тестах?
- Тестируется ли свой хендлер через NewRecorder без сети?
- Покрыты ли коды ошибок, таймауты, битый/пустой JSON?
`,
  sources: `
- Пакеты net/http, net/http/httptest, errors, encoding/json (go.dev).
- Error handling in Go (go.dev/blog); учебник по Go (подключён в модуле).
`,
});
